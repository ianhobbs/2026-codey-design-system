 *
 * ── THE VALUES, WHICH ARE YOURS ───────────────────────────────────────
 *
 * Widths, qualities and the 2560 ceiling are DEFAULTS, not doctrine. The
 * ceiling is only correct if your masters reach it: KIRBY DOES NOT UPSCALE, so
 * a master narrower than a step silently yields a smaller file while the
 * descriptor still claims the full width — the same lie as above, per-image.
 *
 * If your masters are smaller, drop the top steps rather than shipping
 * descriptors that overstate them. Override by merging your own array over
 * this one in config.php; do not edit this file — it is overwritten wholesale
 * on a Codey update.
