 * tells every browser the file is 10% narrower than it is, and they select
 * accordingly. That bug is invisible in the Panel, invisible in the rendered
 * page, and only shows up if you compare a descriptor against the file it
 * names — which is why the rule lives in core rather than in a comment on a
 * project's config.
 *
 * Steps are ~1.33x apart: close enough that the chosen candidate is never much
 * bigger than the slot, far enough apart that the thumb count stays sane. All
 * three ladders are identical so the avif / webp / fallback paths cannot
